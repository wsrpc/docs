"""Export API documentation from a library checkout without importing it.

Usage: uv run python tools/export_api.py ../wsrpc-asgi asgi
Only signatures and docstrings are exported, never implementation bodies.
"""

import argparse
import ast
import copy
import subprocess
import textwrap
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def signature(node):
    args = copy.deepcopy(node.args)
    positional = args.posonlyargs + args.args
    if positional and positional[0].arg in {"self", "cls"}:
        if args.posonlyargs:
            args.posonlyargs.pop(0)
        else:
            args.args.pop(0)
    return ast.unparse(args)


def describe(node, indent=""):
    doc = ast.get_docstring(node)
    return textwrap.indent(doc, indent) + "\n\n" if doc else ""


def export(source: Path, section: str):
    metadata = tomllib.loads((source / "pyproject.toml").read_text())
    package = metadata["project"]["name"].replace("-", "_")
    package_root = source / package
    classes = {}
    nodes = {}
    # The abstract classes repeat concrete class names; document public
    # concrete implementations and their shared route bases instead.
    for path in [
        package_root / "signal.py",
        *sorted((package_root / "websocket").glob("*.py")),
    ]:
        if path.name == "abc.py":
            continue
        tree = ast.parse(path.read_text())
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                classes[node.name] = node
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                nodes[(path.stem, node.name)] = node

    def inherited(name, visited=None):
        visited = set() if visited is None else visited
        if name in visited or name not in classes:
            return {}
        visited.add(name)
        node = classes[name]
        members = {}
        for base in node.bases:
            if isinstance(base, ast.Subscript):
                base = base.value
            if isinstance(base, ast.Name):
                members.update(inherited(base.id, visited))
        for child in node.body:
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef)):
                members[child.name] = child
        return members

    exported = [
        "WSRPCBase",
        "WSRPCClient",
        "WebSocketBase",
        "WebSocketAsync",
        "WebSocketThreaded",
        "Route",
        "AllowedRoute",
        "PrefixRoute",
        "WebSocketRoute",
        "ClientException",
        "WSRPCError",
    ]
    if section == "asgi":
        exported += ["RPCApplication", "RPCMiddleware"]
    title = f"{metadata['project']['name']} API"
    revision = subprocess.check_output(
        ["git", "rev-parse", "HEAD"],
        cwd=source,
        text=True,
    ).strip()
    out = [
        title,
        "=" * len(title),
        "",
        ".. Generated by tools/export_api.py from library docstrings.",
        "",
        f"Signatures from version {metadata['project']['version']}",
        f"(source revision ``{revision}``).",
        "",
        "This reference is checked in so builds do not require",
        "installing the library or accessing its source repository.",
        "",
        f".. py:module:: {package}",
        "",
    ]
    for name in exported:
        node = classes[name]
        members = inherited(name)
        init = members.get("__init__")
        args = f"({signature(init)})" if init else ""
        out += [name, "-" * len(name), "", f".. py:class:: {name}{args}", ""]
        out += [describe(node, "   ").rstrip(), ""]
        for member_name, child in members.items():
            if member_name.startswith("_"):
                continue
            decorators = {ast.unparse(item) for item in child.decorator_list}
            kind = "property" if "property" in decorators else "method"
            suffix = "" if kind == "property" else f"({signature(child)})"
            out += [f"   .. py:{kind}:: {member_name}{suffix}"]
            for option in ("classmethod", "staticmethod"):
                if option in decorators:
                    out.append(f"      :{option}:")
            if isinstance(child, ast.AsyncFunctionDef):
                out.append("      :async:")
            out += ["", describe(child, "      ").rstrip(), ""]
        out.append("")
    out += [
        "Serialization",
        "-------------",
        "",
        ".. py:data:: STATIC_DIR",
        "",
        "   Installed JavaScript clients and TypeScript declarations.",
        "",
        ".. py:function:: serializer(value)",
        "",
        describe(nodes[("tools", "serializer")], "   ").rstrip(),
        "",
    ]
    for module, names in (
        ("websocket.decorators", ("proxy", "noproxy")),
        ("signal", ("receiver",)),
    ):
        out += [f".. py:module:: {package}.{module}", ""]
        for name in names:
            node = nodes[(module.rsplit(".", 1)[-1], name)]
            out += [
                f".. py:function:: {name}({signature(node)})",
                "",
                describe(node, "   ").rstrip(),
                "",
            ]
    signal = classes["Signal"]
    out += [".. py:class:: Signal()", "", describe(signal, "   ").rstrip(), ""]
    for name, node in inherited("Signal").items():
        if name.startswith("_"):
            continue
        is_property = any(
            ast.unparse(item) == "property" for item in node.decorator_list
        )
        directive = "property" if is_property else "method"
        suffix = "" if is_property else f"({signature(node)})"
        out += [
            f"   .. py:{directive}:: {name}{suffix}",
            "",
            describe(node, "      ").rstrip(),
            "",
        ]
    destination = ROOT / section / "api.rst"
    destination.write_text("\n".join(out).rstrip() + "\n")
    print(destination.relative_to(ROOT))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("section", choices=("aiohttp", "asgi"))
    args = parser.parse_args()
    export(args.source.resolve(), args.section)
